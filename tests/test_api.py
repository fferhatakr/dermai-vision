"""
WHY ARE THESE TESTS HERE?
API = the point of contact with the user (Streamlit, mobile app, hospital system).
If the /analyze endpoint breaks → the user cannot get results.
If /login returns a 500 error → nobody can log in to the system.

These tests verify that the API works correctly from the OUTSIDE.
They do not concern themselves with internal models, databases, etc. — only:
"When I send this data to this URL, does it return the correct format?"


HTTP STATUS CODES:
200 = Success
400 = Bad request (missing parameters, etc.)
401 = Unauthorised (no token or incorrect token)
403 = Forbidden (token present but no authorisation)
422 = Invalid data format
500 = Server error (there is a bug in our code)
"""


import  pytest 
